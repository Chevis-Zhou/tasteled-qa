import * as fs from "node:fs";
import * as path from "node:path";
import { failures, verdictOf, warnings, type QAResult } from "./types.js";

/** Writes `report.html` and `report.json`. Verdict first, failures as expected-vs-actual,
 * warnings below, screenshots last. */

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

export function writeReport(result: QAResult, screenshots: string[], outDir: string): { html: string; json: string } {
  fs.mkdirSync(outDir, { recursive: true });

  const verdict = verdictOf(result);
  const fails = failures(result);
  const warns = warnings(result);
  const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;
  const verdictLine =
    verdict === "FAIL"
      ? `FAIL: ${plural(fails.length, "failure", "failures")}`
      : verdict === "WARN"
        ? `WARN: ${plural(warns.length, "warning", "warnings")}`
        : "PASS";

  const failRows = fails
    .map(
      (f) =>
        `<tr><td>${esc(f.check)}</td><td>${esc(f.message)}</td><td>${esc(f.url ?? "")}</td><td><code>${esc(f.selector ?? "")}</code></td><td>${esc(f.expected ?? "")}</td><td>${esc(f.actual ?? "")}</td></tr>`,
    )
    .join("\n");
  const warnRows = warns
    .map((f) => `<li><strong>${esc(f.check)}</strong>: ${esc(f.message)}${f.url ? ` <span class="muted">${esc(f.url)}</span>` : ""}</li>`)
    .join("\n");
  const scores = result.results.find((r) => r.evidence?.lighthouse)?.evidence?.lighthouse as
    | Record<string, Record<string, number>>
    | undefined;
  const scoreRows = scores
    ? Object.entries(scores)
        .map(([u, s]) => `<tr><td>${esc(u)}</td><td>${s.accessibility}</td><td>${s.seo}</td><td>${s.bestPractices}</td><td>${s.performance}</td></tr>`)
        .join("\n")
    : "";
  const shots = screenshots
    .map((p) => {
      const rel = path.relative(outDir, p);
      return `<figure><a href="${esc(rel)}"><img src="${esc(rel)}" alt="${esc(path.basename(p))}" loading="lazy"></a><figcaption>${esc(path.basename(p))}</figcaption></figure>`;
    })
    .join("\n");

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>tasteled-qa: ${esc(verdictLine)}</title>
<style>
  body { font: 14px/1.5 -apple-system, system-ui, sans-serif; margin: 2rem; color: #1a1a1a; max-width: 1400px; }
  h1 { font-size: 1.25rem; letter-spacing: 0.02em; margin-bottom: 0.25rem; }
  .FAIL { color: #b91c1c; } .WARN { color: #b45309; } .PASS { color: #15803d; }
  .muted { color: #666; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: 0.85rem; }
  th, td { border: 1px solid #ddd; padding: 0.4rem 0.6rem; text-align: left; vertical-align: top; }
  th { background: #f5f5f5; }
  figure { display: inline-block; margin: 0.5rem; vertical-align: top; }
  figure img { width: 240px; max-height: 480px; object-fit: cover; object-position: top; border: 1px solid #ddd; }
  figcaption { font-size: 0.75rem; color: #666; }
  footer { margin-top: 3rem; font-size: 0.8rem; color: #666; }
</style>
</head>
<body>
<h1 class="${verdict}">${esc(verdictLine)}</h1>
<p class="muted">${esc(result.target)} · ${result.pages.length} page(s) · ${esc(result.ranAt)}</p>

<h2>Failures (${fails.length})</h2>
<table>
<thead><tr><th>Check</th><th>Message</th><th>URL</th><th>Selector</th><th>Expected</th><th>Actual</th></tr></thead>
<tbody>
${failRows || '<tr><td colspan="6">None</td></tr>'}
</tbody>
</table>

<h2>Warnings (${warns.length})</h2>
<ul>
${warnRows || "<li>None</li>"}
</ul>
${
  scoreRows
    ? `<h2>Lighthouse</h2>
<table><thead><tr><th>Page</th><th>Accessibility</th><th>SEO</th><th>Best practices</th><th>Performance (recorded only)</th></tr></thead>
<tbody>${scoreRows}</tbody></table>`
    : ""
}
<h2>Screenshots</h2>
${shots || "<p>None captured.</p>"}

<footer>Generated by <a href="https://github.com/Chevis-Zhou/tasteled-qa">tasteled-qa</a>, the QA gate from <a href="https://tasteled.com">TasteLed</a>.</footer>
</body>
</html>
`;

  const json = JSON.stringify(
    { verdict, failureCount: fails.length, warningCount: warns.length, ...result },
    null,
    2,
  );

  const htmlPath = path.join(outDir, "report.html");
  const jsonPath = path.join(outDir, "report.json");
  fs.writeFileSync(htmlPath, html);
  fs.writeFileSync(jsonPath, json);
  return { html: htmlPath, json: jsonPath };
}
